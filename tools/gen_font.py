#!/usr/bin/env python3
"""Generates src/font_data.c (anti-aliased 8-bit glyph atlases) from DejaVu Sans.
Run:  python3 tools/gen_font.py   (needs Pillow + fonts-dejavu). The generated file is committed,
so you only need this if you want to change sizes/glyphs. DejaVu fonts are freely redistributable."""
import os, sys
from PIL import ImageFont

REG = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
FONTS = [("small", REG, 20), ("body", REG, 26), ("bold", BOLD, 26), ("title", BOLD, 44)]
EXTRA = [0x2122, 0x2019, 0x2018, 0x201C, 0x201D, 0x2013, 0x2014, 0x2026, 0x2022, 0x20AC]
CPS = list(range(32, 127)) + list(range(160, 256)) + EXTRA

out = ['/* GENERATED by tools/gen_font.py - DejaVu Sans (free license). Do not edit. */',
       '#include "font.h"', '']
tables = []
for name, path, size in FONTS:
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    data, glyphs = [], []
    for cp in CPS:
        ch = chr(cp)
        adv = int(round(f.getlength(ch)))
        l, t, r, b = f.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        off = len(data)
        if w and h and ch != " ":
            mask = f.getmask(ch, mode="L")
            # render through an image to get exact bbox placement
            from PIL import Image, ImageDraw
            im = Image.new("L", (w + 2, h + 2), 0)
            ImageDraw.Draw(im).text((-l + 1, -t + 1), ch, font=f, fill=255, anchor="ls")
            w, h = im.size
            data.extend(im.tobytes())
            glyphs.append((cp, adv, w, h, l - 1, t - 1, off))
        else:
            glyphs.append((cp, adv, 0, 0, 0, 0, off))
    out.append(f'static const unsigned char {name}_px[] = {{')
    for i in range(0, len(data), 24):
        out.append(' ' + ','.join(str(v) for v in data[i:i + 24]) + ',')
    if not data: out.append(' 0,')
    out.append('};')
    out.append(f'static const FontGlyph {name}_gl[] = {{')
    for g in glyphs:
        out.append(' {%d,%d,%d,%d,%d,%d,%d},' % g)
    out.append('};')
    out.append(f'const Font font_{name} = {{ {asc + desc}, {asc}, {len(glyphs)}, {name}_gl, {name}_px }};')
    out.append('')
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "font_data.c")
open(dst, "w").write("\n".join(out))
print("wrote", dst, os.path.getsize(dst) // 1024, "KB")
